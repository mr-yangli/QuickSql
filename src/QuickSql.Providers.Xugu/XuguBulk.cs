namespace QuickSql.Providers.Xugu;

/// <summary>虚谷的批量声明：高速面只有 L3 多值 VALUES + L5 逐条两档（没有装载通道——驱动 XuguClient.dll 的
/// XG* 导出类型面里没有任何装载类，二进制扫描实测；重开条件见 <see cref="XuguProvider.Bulk"/>）。
///
/// <para><b>双数落账：安全界 2048，性能终值 300（2026-11-18 活库实测）</b>。
/// 安全界出处（obj/logs/xugu-budget-probe-2.log）：净室探针在 TESTDB 上以「一尝试一连接」梯子量出收/拒边界——
/// 3 列梯 2046 颗收、2049 颗拒，1 列梯 2048 颗收、2049 颗拒，两颗边界钉在同一点：
/// <b>限的是参数颗数 2048（2^11，协议字段形），不是语句文本长</b>（边界处两梯 SQL 文本 14.3 KB vs 17.0 KB
/// 不同而颗数同；1 列 2000 颗 16.5 KB 收、3 列 2061 颗 14.4 KB 拒）。超限的失败形状是服务端直接断连接
/// （「远程主机强迫关闭了一个现有的连接」）而不是干净报错；边界内 2046/1842 颗带主键全行读回错绑 0
/// （probe-4/5.log；读回须另开连接——同连接看不见刚提交的写，见 notes.md 探针方法学三颗）。
///
/// <para>性能终值出处（BDN A/B，1000×30，obj/logs/net11-bdn-xugu-*.log）：LongRun 兜底 100=409.1ms±8.5、
/// 硬上限 2048=702.7ms±5.5——<b>照硬上限声明宽块时间输 1.72×</b>；medium 扫描 200=340.5±19.8 /
/// 300=346.6±12.6 / 600=381.0±14.6 / 1000=452.8±12.9，谷底平在 200–300，取 <b>300</b>
/// （29 列每块 9 行、1000 行 112 块；比 200 少一半往返，利于远程库缩放；LongRun 定案 345.0ms±4.2，
/// 对 100 腿 CI 不重叠、快约 16%，对 2048 腿快 2.04×，分配 22.89 vs 23.22 MB 亦省）。
/// 机制（xugu-budget-sweep-1.log，暖连接单事务逐语句计时）：服务端每语句代价随颗数<b>超线性</b>
/// （87 颗≈0.4ms / 435 颗 6ms / 899 颗 11ms / 1827 颗 39ms），总时间=语句数×每语句代价 的极点不在最大块宽——
/// 与 SQLite 族驱动侧按名查找平方价<b>同课不同源</b>：硬上限是安全界，不是性能最优界。
/// sweep 的暖连接长事务形状低估宽块绝对值（31 行估 363ms 而 BDN 452.8ms），只定机制与形状、不定终值。</para>
///
/// <para>IN 列表臂不另覆写（默认跟 ParameterBudget）：谓词链与 VALUES 臂走同一颗驱动的同一套参数机制，
/// 颗数界限对两臂同形；SQLite 那种「两臂分预算」的理由（按名查找平方价）在本家没有读数支撑。</para>
///
/// <para><b>另一颗与参数无关的界限（实测 E14024）</b>：单事务改行上限 10000（系统参数 max_trans_modify）。
/// 多块插入由执行段包一条事务，所以单批 &gt;10000 行在这一家会撞它——与块宽无关、与本预算无关
/// （兜底 100 的时代同撞），是事务收口政策与库侧上限的交点；要不要为它拆事务是原子性语义的裁决，不在本槽射程。
/// 探针清夹具时整表一句 DELETE 24907 行撞的就是这颗；树形册万节点用例的 finally 删 10000 行恰在界内。</para></summary>
public sealed class XuguBulk : IBulkStrategy
{
    public int ParameterBudget => 300;

    public string Describe =>
        "L3 多值 VALUES + L5 逐条（没有装载通道：驱动 XG* 类型面无装载类）；参数预算 300（BDN 实测时间拐点）"
        + "，安全界 2048（活库实测：2048 颗收 / 2049 颗拒且断连接，3 列/1 列两梯边界同点，限颗数不限文本长）";
}